## Lo que sí puedes hacer en casa mientras tanto

Nada de esto reemplaza lo anterior. Es lo que le da al lenguaje con qué crecer, y
es gratis.

- **Habla en voz alta lo que están haciendo**: "estoy pelando el verde", "esta
