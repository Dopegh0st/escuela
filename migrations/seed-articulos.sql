## De 12 a 18 meses

- Aparecen las primeras palabras con sentido: *mamá*, *papá*, *agua*, *dame*, *no*.
  Suelen ser pocas y mal pronunciadas, y eso es lo normal.
- Responde a su nombre y voltea.
- **Señala** lo que quiere y lo que le llama la atención, y te mira a ti para
  compartirlo. Señalar es de lo más importante de esta etapa.
- Sigue órdenes de un paso sin gestos: "dame la pelota".
- Balbucea con entonación, como si conversara.

## De 18 a 24 meses

Acá suele haber un salto grande, y es donde más se nota la diferencia entre uno y
otro.

- Hacia los dos años, la mayoría llega a **unas 50 palabras distintas** y empieza
  a **juntar dos**: "quiero agua", "no quiero", "papá vamos".
- Sigue instrucciones de dos pasos: "agarra tus medias y dáselas a tu hermano".
- Nombra partes del cuerpo y objetos de la casa.
- Alguien de fuera de la familia le entiende **más o menos la mitad** de lo que
  dice. En casa le entienden mucho más, porque ya conocen sus versiones.

## De 2 a 3 años

- El vocabulario crece rápido: ya son cientos de palabras.
- Arma frases de tres o cuatro palabras y empieza a usar el pasado, aunque lo arme
  mal ("se rompió", "yo poní").
- Cuenta algo que le pasó, en desorden y con huecos, pero lo cuenta.
- Pregunta mucho.
- Hacia los tres años, una persona de fuera le entiende **alrededor de tres
  cuartas partes** de lo que dice.

## De 3 a 4 años

- Habla en frases completas y sostiene una conversación de ida y vuelta.
- El "¿por qué?" no para. Es buena señal, aunque agote.
- Cuenta un cuento corto o lo que hizo en la escuela.
- Todavía cambia sonidos difíciles, y eso está dentro de lo esperado.

## De 4 a 5 años

- Casi todo se le entiende, incluso alguien que no lo conoce.
- Cuenta algo en orden: primero pasó esto, después esto.
- Sigue instrucciones de tres pasos.
- **Le pueden seguir costando** la *r* vibrante, la *rr* y grupos como *tr*,
  *pl*, *br*, *cr*. Decir "pato" por "plato" o "cara" por "carro" a los cuatro
  años es común.

## De 5 a 6 años

- La *r* y la *rr* suelen acomodarse en este tramo.
- Entiende chistes y adivinanzas.
- Empieza a relacionar el sonido con la letra: es la puerta a la lectura.
- Usa el lenguaje para negociar, inventar y explicar, no solo para pedir.

## Los cuatro mitos que más confunden

**"Dos idiomas en la casa lo atrasan."** No. Un niño que crece con kichwa y
español, o con español e inglés, reparte su vocabulario entre las dos lenguas: si
cuentas solo una parece que va atrás, y si sumas las dos la cuenta cuadra. Y si un
niño bilingüe tiene una dificultad real, la tiene en **las dos** lenguas.

**"Los varones hablan más tarde."** En promedio la diferencia es mínima. No
alcanza ni de cerca para explicar un retraso marcado, y usarla como explicación es
la manera más común de perder un año.

**"Ya hablará solito."** A veces sí. El problema es que desde afuera no se
distingue al que va a arrancar solo del que no, y la única forma de averiguarlo es
esperando. Preguntar no cuesta nada; esperar un año cuesta un año.

**"Es que ve mucha pantalla."** La pantalla no enseña a hablar, y no porque sea
mala en sí: porque **no responde**. Un niño aprende hablando con alguien que le
contesta y lo espera; una tablet nunca espera. Igual con el hermano mayor que
traduce todo: si alguien le adivina siempre lo que quiere, hablar deja de hacer
falta.

