- **Repite bien, sin corregir.** Si dice "el ato", tú dices "sí, el gato". No le
  pidas que lo repita ni le digas que está mal; solo devuélveselo bien dicho.
- **Estira la frase una palabra.** Si dice "quiero agua", tú dices "quieres agua
