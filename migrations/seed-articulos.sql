- **Cuentos todos los días**, aunque sean cinco minutos y sea el mismo cuento por
  décima vez: la repetición es justamente donde aprende.
- **Apaga la tele de fondo** mientras comen o juegan: el ruido tapa precisamente
  las palabras que necesita escuchar.
