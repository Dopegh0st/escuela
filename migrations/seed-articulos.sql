Si llevas tres o cuatro semanas con hora fija, tiempos razonables y
acompañamiento al inicio, y la cosa sigue igual de dura, el problema ya no es la
rutina. Ahí toca averiguar qué es.

Puede ser algo sencillo de descartar primero —vista, oído, sueño— y eso está en
[por dónde empezar cuando un niño no quiere hacer las tareas](/blog/mi-hijo-no-quiere-hacer-tareas/).
Puede ser algo específico de una materia. Puede ser algo del curso que en casa no
se ve.

En cualquiera de esos casos la siguiente conversación no es con tu hijo, es con
la profesora, y conviene llevarla preparada:
[qué preguntar y cómo pedir la reunión](/blog/como-hablar-con-la-profesora-de-tu-hijo/).

## Lo que no ayuda

Quitar el recreo del fin de semana para "ponerse al día". Comparar con el hermano
que sí se sienta solo. Hacerle el deber a las once de la noche para que no llegue
sin nada —el docente se da cuenta, y lo que aprende el niño es que si estira lo
suficiente, aparece alguien—. Y prometer castigos que después no vas a cumplir.

