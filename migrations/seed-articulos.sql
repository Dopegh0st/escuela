## Dos ideas que cambian cómo se leen las listas

**Entender viene antes que decir.** Un niño de año y medio que dice cuatro
palabras pero entiende todo lo que le pides, señala lo que quiere y te trae el
zapato cuando se lo nombras está haciendo casi todo el trabajo. La parte que
falta es la más visible, no la más importante.

**El rango normal es ancho de verdad.** Dos niños perfectamente típicos pueden
llevarse ocho o diez meses de diferencia en cuándo empiezan a armar frases. Por eso
las listas de abajo van en rangos, y por eso una sola casilla sin marcar no
